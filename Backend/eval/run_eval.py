"""Evaluation harness for the numbers section 8 asks for.

Everything here is computed from real rows or real model calls. Nothing is
estimated, and a missing measurement prints as "not measured" rather than 0.

    cd Backend
    .venv\\Scripts\\python.exe -m eval.run_eval             # database numbers
    .venv\\Scripts\\python.exe -m eval.run_eval --labels    # + accuracy on photos

`--labels` reads eval/labels.csv (see labels.example.csv) and runs the vision
model on each file in eval/photos/. That costs one model call per photo.
"""
import argparse
import csv
import json
import statistics
from pathlib import Path

from sqlalchemy import text

from api.database import engine

PHOTOS_DIR = Path("eval/photos")
LABELS_CSV = Path("eval/labels.csv")


def latency() -> dict | None:
    """Submission to first analysis, in seconds, from the status timeline."""
    with engine.connect() as conn:
        rows = conn.execute(
            text(
                """
                select r.id,
                       min(e.created_at) filter (where e.status = 'received') as received_at,
                       min(e.created_at) filter (where e.status = 'analysed') as analysed_at
                from reports r
                join status_events e on e.report_id = r.id
                group by r.id
                """
            )
        ).mappings().all()

    seconds = sorted(
        (row["analysed_at"] - row["received_at"]).total_seconds()
        for row in rows
        if row["received_at"] and row["analysed_at"]
    )
    if not seconds:
        return None

    index = min(len(seconds) - 1, int(len(seconds) * 0.9))
    return {
        "n": len(seconds),
        "median_s": round(statistics.median(seconds), 1),
        "p90_s": round(seconds[index], 1),
        "min_s": round(seconds[0], 1),
        "max_s": round(seconds[-1], 1),
    }


def coverage() -> dict:
    """How much of the pipeline actually ran, per report."""
    with engine.connect() as conn:
        row = conn.execute(
            text(
                """
                select count(*) as total,
                       count(*) filter (where issue_type is not null) as typed,
                       count(*) filter (where severity_level is not null) as scored,
                       count(*) filter (where status = 'needs_better_photo') as rejected_photo,
                       count(*) filter (where status = 'needs_review') as needs_review,
                       count(*) filter (where ai_result ? 'routing') as routing_records,
                       count(*) filter (
                           where (ai_result -> 'routing' -> 'delivery' ->> 'ok')::boolean
                       ) as delivered,
                       count(*) filter (
                           where (ai_result -> 'routing' -> 'inside_pilot_area')::boolean = false
                       ) as outside_area,
                       count(*) filter (where ai_result ? 'duplicate_suggestion') as duplicate_suggested,
                       count(*) filter (
                           where ai_result -> 'duplicate_suggestion' ->> 'response' = 'same'
                       ) as duplicate_merged,
                       count(*) filter (where status = 'resolved') as resolved
                from reports
                """
            )
        ).mappings().first()
    return dict(row)


def score_labels() -> dict | None:
    """Issue-type accuracy against hand-labelled photos, one model call each."""
    if not LABELS_CSV.is_file():
        return None

    from ai.vision import VisionUnavailable, analyse_image

    with LABELS_CSV.open(encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))

    per_type: dict[str, dict] = {}
    correct = 0
    skipped = 0

    for row in rows:
        photo = PHOTOS_DIR / (row.get("filename") or "").strip()
        expected = (row.get("issue_type") or "").strip()
        if not expected or not photo.is_file():
            skipped += 1
            continue
        try:
            result, _model = analyse_image(photo.read_bytes(), row.get("note") or None)
        except VisionUnavailable:
            skipped += 1
            continue

        bucket = per_type.setdefault(expected, {"n": 0, "right": 0})
        bucket["n"] += 1
        if result.issue_type == expected:
            correct += 1
            bucket["right"] += 1

    total = sum(bucket["n"] for bucket in per_type.values())
    return {
        "n": total,
        "skipped": skipped,
        "accuracy": round(correct / total, 3) if total else None,
        "per_type": per_type,
    }


def render(lat: dict | None, cov: dict, labels: dict | None) -> str:
    lines = [
        "# Evaluation",
        "",
        "Generated by `python -m eval.run_eval` from the live database.",
        "Every number below is measured; anything unmeasured is written as such.",
        "",
        "## Latency: submission to first analysis",
        "",
    ]
    if lat:
        lines += [
            "| Reports | Median | 90th percentile | Fastest | Slowest |",
            "|---|---|---|---|---|",
            f"| {lat['n']} | {lat['median_s']} s | {lat['p90_s']} s | {lat['min_s']} s | {lat['max_s']} s |",
        ]
    else:
        lines.append("Not measured: no report has both a `received` and an `analysed` event yet.")

    total = cov.get("total") or 0
    pct = (lambda n: f"{round(100 * n / total)}%" if total else "n/a")

    lines += [
        "",
        "## Pipeline coverage",
        "",
        "| Stage | Reports | Share |",
        "|---|---|---|",
        f"| Filed | {total} | 100% |",
        f"| Classified (issue type) | {cov['typed']} | {pct(cov['typed'])} |",
        f"| Severity scored | {cov['scored']} | {pct(cov['scored'])} |",
        f"| Rejected for a clearer photo | {cov['rejected_photo']} | {pct(cov['rejected_photo'])} |",
        f"| Needs review | {cov['needs_review']} | {pct(cov['needs_review'])} |",
        f"| Routing attempted | {cov['routing_records']} | {pct(cov['routing_records'])} |",
        f"| Complaint delivered | {cov['delivered']} | {pct(cov['delivered'])} |",
        f"| Outside the pilot area | {cov['outside_area']} | {pct(cov['outside_area'])} |",
        f"| Duplicate suggested | {cov['duplicate_suggested']} | {pct(cov['duplicate_suggested'])} |",
        f"| Duplicate merged | {cov['duplicate_merged']} | {pct(cov['duplicate_merged'])} |",
        f"| Resolved | {cov['resolved']} | {pct(cov['resolved'])} |",
        "",
        "## Classification accuracy",
        "",
    ]

    if labels and labels["accuracy"] is not None:
        lines += [
            f"Hand-labelled photos scored: **{labels['n']}** (skipped {labels['skipped']}).",
            "",
            f"**Accuracy: {round(labels['accuracy'] * 100, 1)}%**",
            "",
            "| Expected type | Photos | Correct |",
            "|---|---|---|",
        ]
        for name, bucket in sorted(labels["per_type"].items()):
            lines.append(f"| {name} | {bucket['n']} | {bucket['right']} |")
    else:
        lines += [
            "Not measured yet.",
            "",
            "1. Put photos in `eval/photos/`.",
            "2. Copy `eval/labels.example.csv` to `eval/labels.csv` and fill one row per photo.",
            "3. Run `python -m eval.run_eval --labels`.",
        ]

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--labels", action="store_true", help="also score labelled photos")
    parser.add_argument("--out", default="eval/report.md")
    args = parser.parse_args()

    lat = latency()
    cov = coverage()
    labels = score_labels() if args.labels else None

    markdown = render(lat, cov, labels)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(markdown, encoding="utf-8")

    print(markdown)
    print(f"written to {out}")
    print(json.dumps({"latency": lat, "coverage": cov, "labels": labels}, default=str))


if __name__ == "__main__":
    main()
